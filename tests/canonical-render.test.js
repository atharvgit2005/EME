test('approved edit persists, restarts, renders canonical trims/order/caption/effect/audio and immutable snapshot',()=>{
  const {root,store}=workspace(), p=fixture(root), {result,projectPath}=commit(p,root,store);
  const snapshot=loadCommittedSnapshot(result.execution_id,store);
  assert(Object.isFrozen(snapshot.project));
  const disk=JSON.parse(fs.readFileSync(projectPath));disk.clips[0].source.trimInTick=0;fs.writeFileSync(projectPath,JSON.stringify(disk));
  const runner=`const R=require(${JSON.stringify(require.resolve('../src/prompt-core/render-orchestrator.js'))}).RenderOrchestrator; console.log(JSON.stringify(R.renderCommitted(JSON.parse(process.argv[1]))));`;
  const rendered=JSON.parse(command(process.execPath,['-e',runner,JSON.stringify({executionId:result.execution_id,outputDir:root,storageDir:store})]));
  assert.equal(rendered.rendered,true);assert.equal(rendered.qaPassed,false);
  assert.equal(rendered.provenance.snapshot_sha256,digest(result.project));
  const first=pixel(frame(rendered.outputPath,.1),20,20), second=pixel(frame(rendered.outputPath,1.5),100,60);
  assert(pixel(frame(rendered.outputPath,1.5),20,20).every(v=>v<10),'Scaled and translated clip leaves the canonical black canvas visible');
  assert(first[1]>80 && first[0]<20 && first[2]<20,JSON.stringify(first));
  assert(second[0]>200 && second[1]>200 && second[2]<40,JSON.stringify(second));
  const before=frame(rendered.outputPath,.2), during=frame(rendered.outputPath,.5), after=frame(rendered.outputPath,.8);
  const whites=b=>{let count=0;for(let i=0;i<b.length;i+=3)if(b[i]>200&&b[i+1]>200&&b[i+2]>200)count++;return count;};
  assert(whites(during)>100);assert.equal(whites(before),0);assert.equal(whites(after),0);
  assert(rms(rendered.outputPath,1.4)>rms(rendered.outputPath,.1)*7);
  console.log('CANONICAL_ARTIFACT '+JSON.stringify({path:rendered.outputPath,sha256:rendered.sha256,provenance:rendered.provenance,first,second}));
});
